<details class="explain">
    <summary>How are these rankings decided?</summary>
    <ol>
        <li>For every week left through week 17, the site takes each team's <b>current roster</b> and Sleeper's projected points for every player that week, scored with this league's own settings.</li>
        <li>It fills the league's starting lineup (including flex spots) with the highest-projected players available that week, the way you would if you set a perfect lineup.</li>
        <li>It adds up those best-lineup projections for all remaining weeks.</li>
        <li>The team with the biggest total gets <b>100</b>. Everyone else is shown as a percentage of that team, so 90 means 90% of the leader's projected points.</li>
    </ol>
    <p><b>What it does not count:</b> your record, points already scored, who you play, or trades that haven't happened. Players on bye project zero for that week, and players ruled out usually do too. Projections come from Sleeper and refresh about once a day, so a big injury can take a day to show up.</p>
</details>

